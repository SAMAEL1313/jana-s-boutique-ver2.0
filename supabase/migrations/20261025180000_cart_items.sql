-- Shopping bags saved on the customer's account, so the bag follows them
-- across devices and is never shared between accounts on one browser.

create table public.cart_items (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users (id) on delete cascade,
  product_id bigint not null references public.products (id) on delete cascade,
  -- '' for products without sizes, so the unique key below works.
  size text not null default '',
  quantity integer not null check (quantity > 0),
  created_at timestamptz not null default now(),
  unique (user_id, product_id, size)
);

alter table public.cart_items enable row level security;

-- Replaces a user's whole bag in one transaction.
-- p_items: [{ product_id, quantity, size }]
create function public.set_cart(p_user_id bigint, p_items jsonb)
returns void
language plpgsql
set search_path = ''
as $$
begin
  delete from public.cart_items where user_id = p_user_id;

  insert into public.cart_items (user_id, product_id, size, quantity)
  select p_user_id, i.product_id, coalesce(i.size, ''), sum(i.quantity)
  from jsonb_to_recordset(coalesce(p_items, '[]'::jsonb)) as i(product_id bigint, quantity integer, size text)
  join public.products p on p.id = i.product_id
  where i.quantity > 0
  group by i.product_id, coalesce(i.size, '');
end;
$$;

revoke execute on function public.set_cart(bigint, jsonb) from public, anon, authenticated;
grant execute on function public.set_cart(bigint, jsonb) to service_role;
