-- Jana's Boutique schema.
--
-- The app only reaches these tables from its API routes, using the Supabase
-- secret key, which bypasses Row Level Security. RLS is enabled with no
-- policies so the public (anon) key can't read or write anything.

-- ---------- helpers ----------

create function public.set_updated_at() returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

-- ---------- tables ----------

-- App accounts (customers and admins). Separate from Supabase Auth's auth.users.
create table public.users (
  id bigint generated by default as identity primary key,
  first_name text not null,
  last_name text not null,
  email text not null unique,
  password_hash text not null,
  is_admin boolean not null default false,
  reset_token_hash text unique,
  reset_token_expires timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  -- tops | bottoms | dresses | perfumes | shoes | accessories
  category text not null,
  -- e.g. heels, sandals, bracelets; null for top-level categories
  subcategory text,
  price numeric(10, 2) not null check (price >= 0),
  stock integer not null default 0 check (stock >= 0),
  overview text,
  -- Optional map of size label -> price (used for perfumes)
  features jsonb,
  styling_tip text,
  -- A /images/... path, or a public URL in the product-images storage bucket
  image_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index products_category_subcategory_idx on public.products (category, subcategory);

create table public.orders (
  id bigint generated by default as identity primary key,
  order_number text not null unique,
  billing_id text not null,
  user_id bigint references public.users (id) on delete set null,
  email text not null,
  first_name text not null,
  last_name text not null,
  address text not null,
  city text not null,
  province text not null,
  zip text not null,
  phone text not null,
  country text not null default 'Philippines',
  payment_method text not null,
  shipping_cost numeric(10, 2) not null,
  total_amount numeric(10, 2) not null,
  purchase_date timestamptz not null default now()
);

create index orders_user_id_idx on public.orders (user_id);

create table public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders (id) on delete cascade,
  -- Set to null when the product is deleted; name/price stay as a snapshot.
  product_id bigint references public.products (id) on delete set null,
  name text not null,
  image_url text,
  size text,
  quantity integer not null check (quantity > 0),
  unit_price numeric(10, 2) not null
);

create index order_items_order_id_idx on public.order_items (order_id);

create trigger users_set_updated_at before update on public.users
  for each row execute function public.set_updated_at();
create trigger products_set_updated_at before update on public.products
  for each row execute function public.set_updated_at();

alter table public.users enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

-- ---------- functions ----------

-- Places an order atomically: re-reads prices from the database, decrements
-- stock (failing if there isn't enough), and saves the order with its items.
-- p_items is [{ "product_id": 1, "quantity": 2, "size": "50ml" | null }, ...].
-- Business errors are raised with SQLSTATE 'JB409' so the API can show them.
create function public.place_order(
  p_user_id bigint,
  p_email text,
  p_order_number text,
  p_billing_id text,
  p_shipping jsonb,
  p_payment_method text,
  p_shipping_cost numeric,
  p_items jsonb
) returns bigint
language plpgsql
set search_path = ''
as $$
declare
  v_order_id bigint;
  v_line jsonb;
  v_product public.products;
  v_quantity integer;
  v_size text;
  v_unit_price numeric(10, 2);
  v_subtotal numeric(10, 2) := 0;
begin
  insert into public.orders (
    order_number, billing_id, user_id, email, first_name, last_name, address,
    city, province, zip, phone, country, payment_method, shipping_cost, total_amount
  ) values (
    p_order_number, p_billing_id, p_user_id, p_email,
    p_shipping ->> 'firstName', p_shipping ->> 'lastName', p_shipping ->> 'address',
    p_shipping ->> 'city', p_shipping ->> 'province', p_shipping ->> 'zip',
    p_shipping ->> 'phone', coalesce(p_shipping ->> 'country', 'Philippines'),
    p_payment_method, p_shipping_cost, 0
  )
  returning id into v_order_id;

  for v_line in select * from jsonb_array_elements(p_items) loop
    v_quantity := (v_line ->> 'quantity')::integer;
    v_size := nullif(v_line ->> 'size', '');

    -- Lock the row so concurrent orders can't oversell.
    select * into v_product from public.products
      where id = (v_line ->> 'product_id')::bigint
      for update;
    if not found then
      raise exception 'A product in your cart is no longer available.' using errcode = 'JB409';
    end if;
    if v_product.stock < v_quantity then
      raise exception 'Not enough stock for %.', v_product.name using errcode = 'JB409';
    end if;

    update public.products set stock = stock - v_quantity where id = v_product.id;

    -- Prices always come from the database, never from the client.
    v_unit_price := v_product.price;
    if v_size is not null and jsonb_typeof(v_product.features -> v_size) = 'number' then
      v_unit_price := (v_product.features ->> v_size)::numeric;
    end if;

    insert into public.order_items (order_id, product_id, name, image_url, size, quantity, unit_price)
      values (v_order_id, v_product.id, v_product.name, v_product.image_url, v_size, v_quantity, v_unit_price);

    v_subtotal := v_subtotal + v_unit_price * v_quantity;
  end loop;

  update public.orders set total_amount = v_subtotal + p_shipping_cost where id = v_order_id;
  return v_order_id;
end;
$$;

create function public.admin_stats()
returns table (total_products bigint, total_orders bigint, total_earnings numeric)
language sql
stable
set search_path = ''
as $$
  select
    (select coalesce(sum(quantity), 0) from public.order_items),
    (select count(*) from public.orders),
    (select coalesce(sum(total_amount), 0) from public.orders);
$$;

-- Only the server (secret key) may call these.
revoke execute on function public.place_order(bigint, text, text, text, jsonb, text, numeric, jsonb)
  from public, anon, authenticated;
revoke execute on function public.admin_stats() from public, anon, authenticated;
grant execute on function public.place_order(bigint, text, text, text, jsonb, text, numeric, jsonb)
  to service_role;
grant execute on function public.admin_stats() to service_role;

