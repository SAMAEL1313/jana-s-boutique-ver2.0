-- Inventory: suppliers, stock movements, order status.

-- ---------- tables ----------

-- Companies or people the boutique buys its products from.
create table public.suppliers (
  id bigint generated by default as identity primary key,
  name text not null unique,
  contact_person text,
  email text,
  phone text,
  address text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.suppliers enable row level security;

create table public.stock_movements (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id),
  supplier_id bigint references public.suppliers (id),
  quantity integer not null,
  reason text not null check (reason in ('restock', 'sale', 'cancel', 'adjustment')),
  created_at timestamptz not null default now()
);

alter table public.stock_movements enable row level security;

-- adds stock to a pproduct  and loge it in stock_movements
create procedure public.restock_product (
  p_product_id bigint,
  p_supplier_id bigint,
  p_quantity integer
)
language pLpgsqL
set search_path = ''
as $$
begin
-- blocks bad input
  if p_quantity <= 0 then 
    raise exception  'Restock quantity must be more than 0.';
    end if;
  update public.products
    set stock = stock + p_quantity
    where id = p_product_id;

if not found then 
  raise exception 'Product % does not exist.', p_product_id;
  end if;

  insert into public.stock_movements (product_id, supplier_id, quantity, reason)
  values (p_product_id, p_supplier_id, p_quantity, 'restock');
  end;
  $$;

  revoke execute on procedure public.restock_product (bigint, bigint, integer)
  from public, anon, authenticated;

alter table public.orders
 add column status text not null default 'pending'
 check (status in ('pending', 'shipped', 'delivered', 'cancelled'));


-- order cancels trigger below puts the stock back
create procedure public.cancel_order(p_order_id bigint)
Language pLpgsqL
set search_path = ''
as $$
declare
  v_status text;
  begin 
  select status into v_status
  from public.orders
  where id = p_order_id
  for update;

if not found then
raise exception 'Order % does not exist.', p_order_id;
end if;

if v_status = 'cancelled' then
    raise exception 'Order % is already cancelled.', p_order_id;
  end if;

  if v_status = 'delivered' then
    raise exception 'Delivered orders cannot be cancelled.';
  end if;

  update public.orders
    set status = 'cancelled'
    where id = p_order_id;
end;
$$;

revoke execute on procedure public.cancel_order(bigint)
  from public, anon, authenticated;